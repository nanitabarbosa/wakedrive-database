-- Creamos la tabla wakedrive.event_types con la misma estructura que genera Hibernate en el backend.
CREATE TABLE IF NOT EXISTS wakedrive.event_types (
    event_type_id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name                     VARCHAR(50) NOT NULL,
    CONSTRAINT event_types_name_key UNIQUE (name),
    CONSTRAINT event_types_pkey PRIMARY KEY (event_type_id)
);
