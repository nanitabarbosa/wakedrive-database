-- Tabla public.companies (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.companies (
    company_id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    alarm_duration_seconds   INTEGER NOT NULL,
    face_recognition_always  BOOLEAN NOT NULL,
    notify_device_shutdown   BOOLEAN NOT NULL,
    alarm_sound_size         INTEGER,
    logo_size                INTEGER,
    phone                    VARCHAR(10) NOT NULL,
    nit                      VARCHAR(12) NOT NULL,
    email                    VARCHAR(100) NOT NULL,
    name                     VARCHAR(100) NOT NULL,
    address                  VARCHAR(150) NOT NULL,
    alarm_sound_name         VARCHAR(255),
    alarm_sound_path         VARCHAR(255),
    logo_name                VARCHAR(255),
    logo_path                VARCHAR(255),
    status                   VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    city_id                  INTEGER NOT NULL,
    CONSTRAINT companies_nit_key UNIQUE (nit),
    CONSTRAINT companies_pkey PRIMARY KEY (company_id),
    CONSTRAINT ck_companies_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
