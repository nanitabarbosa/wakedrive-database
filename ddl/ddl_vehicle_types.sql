-- Creamos la tabla wakedrive.vehicle_types con la misma estructura que genera Hibernate en el backend.
CREATE TABLE IF NOT EXISTS wakedrive.vehicle_types (
    vehicle_type_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name                     VARCHAR(50) NOT NULL,
    CONSTRAINT vehicle_types_name_key UNIQUE (name),
    CONSTRAINT vehicle_types_pkey PRIMARY KEY (vehicle_type_id)
);
