-- Tabla public.vehicle_types (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.vehicle_types (
    vehicle_type_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name                     VARCHAR(50) NOT NULL,
    CONSTRAINT vehicle_types_name_key UNIQUE (name),
    CONSTRAINT vehicle_types_pkey PRIMARY KEY (vehicle_type_id)
);
