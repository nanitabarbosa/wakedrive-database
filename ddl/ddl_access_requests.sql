-- Tabla public.access_requests (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.access_requests (
    access_request_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    city_id                  BIGINT NOT NULL,
    created_at               TIMESTAMP(6) NOT NULL,
    nit                      VARCHAR(30) NOT NULL,
    address                  VARCHAR(255) NOT NULL,
    admin_email              VARCHAR(255) NOT NULL,
    admin_name               VARCHAR(255) NOT NULL,
    admin_phone              VARCHAR(255) NOT NULL,
    company_name             VARCHAR(255) NOT NULL,
    company_phone            VARCHAR(255) NOT NULL,
    status                   VARCHAR(255) NOT NULL,
    CONSTRAINT access_requests_pkey PRIMARY KEY (access_request_id),
    CONSTRAINT access_requests_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'APPROVED'::character varying, 'REJECTED'::character varying, 'INACTIVE'::character varying])::text[])))
);
