-- Tabla public.vehicles (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.vehicles (
    vehicle_id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    year                     INTEGER NOT NULL,
    brand_id                 BIGINT NOT NULL,
    company_id               BIGINT NOT NULL,
    created_at               TIMESTAMP(6) NOT NULL,
    vehicle_type_id          BIGINT NOT NULL,
    plate                    VARCHAR(15) NOT NULL,
    model                    VARCHAR(255) NOT NULL,
    status                   VARCHAR(255) NOT NULL,
    CONSTRAINT vehicles_plate_key UNIQUE (plate),
    CONSTRAINT vehicles_pkey PRIMARY KEY (vehicle_id),
    CONSTRAINT vehicles_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'INACTIVE'::character varying])::text[])))
);
