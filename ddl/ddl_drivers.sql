-- Tabla public.drivers (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.drivers (
    driver_id                INTEGER GENERATED BY DEFAULT AS IDENTITY,
    company_id               INTEGER NOT NULL,
    created_at               TIMESTAMP(6) NOT NULL,
    document                 VARCHAR(10) NOT NULL,
    phone                    VARCHAR(10) NOT NULL,
    status                   VARCHAR(20) NOT NULL,
    email                    VARCHAR(100),
    full_name                VARCHAR(100) NOT NULL,
    CONSTRAINT drivers_document_key UNIQUE (document),
    CONSTRAINT drivers_pkey PRIMARY KEY (driver_id),
    CONSTRAINT drivers_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'INACTIVE'::character varying])::text[])))
);
