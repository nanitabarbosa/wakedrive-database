-- Tabla public.vinculations (misma estructura que genera Hibernate en el backend)
CREATE TABLE IF NOT EXISTS public.vinculations (
    vinculation_id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_id                INTEGER NOT NULL,
    driver_id                INTEGER NOT NULL,
    linked_at                TIMESTAMP(6) NOT NULL,
    vehicle_id               INTEGER NOT NULL,
    CONSTRAINT vinculations_device_id_key UNIQUE (device_id),
    CONSTRAINT vinculations_driver_id_key UNIQUE (driver_id),
    CONSTRAINT vinculations_vehicle_id_key UNIQUE (vehicle_id),
    CONSTRAINT vinculations_pkey PRIMARY KEY (vinculation_id)
);
